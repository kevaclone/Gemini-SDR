export function findDabEnsembleByFreq(freqHz: number): DabEnsemble | undefined {
  // Matches if tuned within 800 kHz of nominal ensemble center frequency
  return DAB_ENSEMBLES.find((e) => Math.abs(e.freqHz - freqHz) <= 800000);
}

export function findDabBlockByFreq(freqHz: number): DabChannelBlock | undefined {
  return DAB_BAND_III_BLOCKS.find((b) => Math.abs(b.freqHz - freqHz) <= 800000);
}
